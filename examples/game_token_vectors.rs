//! Test vectors for a game server's verifier (`docs/game-token.md`).
//!
//! ```text
//! cargo run --example game_token_vectors -- <output directory> [issuer] [audience]
//! ```
//!
//! `issuer` and `audience` default to `https://identity.example` and
//! `https://game.example`; a deployment passes its own.
//!
//! Writes `game-token-vectors.json`: an identity key set, game tokens with
//! and without the pass, the device key their `cnf` names, request proofs
//! with every input stated, and tokens a verifier must refuse. Each vector
//! is checked here with the reference verifier before it is written.
//!
//! **Every key is generated by this run and is in the output file.** Nothing
//! here is a production key, and the output must never be committed: run it
//! where the vectors are needed.

use authnz_rs::cwt::{self, CwtError};
use authnz_rs::game_token::{self, GameToken};
use authnz_rs::keys::{KeySet, thumbprint_kid};
use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use coset::AsCborValue;
use p256::ecdsa::signature::Signer;
use p256::ecdsa::{Signature, SigningKey};
use p256::elliptic_curve::rand_core::OsRng;
use serde_json::{Value, json};

const SKEW: i64 = 60;

fn b64(bytes: &[u8]) -> String {
    URL_SAFE_NO_PAD.encode(bytes)
}

fn text(bytes: &[u8]) -> String {
    cwt::encode_for_header(bytes)
}

fn raw_signature(key: &SigningKey, message: &str) -> String {
    let sig: Signature = key.sign(message.as_bytes());
    b64(&sig.to_bytes())
}

fn main() {
    let mut args = std::env::args().skip(1);
    let dir = args
        .next()
        .expect("usage: game_token_vectors <output directory> [issuer] [audience]");
    let issuer = args
        .next()
        .unwrap_or_else(|| "https://identity.example".into());
    let audience = args.next().unwrap_or_else(|| "https://game.example".into());
    assert!(game_token::is_audience(&audience), "not a game audience");
    let (issuer, audience) = (issuer.as_str(), audience.as_str());
    let now = chrono::Utc::now().timestamp();

    // Identity's signing key and the set a verifier fetches.
    let identity = SigningKey::random(&mut OsRng);
    let kid = thumbprint_kid(identity.verifying_key()).expect("kid");
    let keys = KeySet::new(*identity.verifying_key(), kid.clone());
    let cose_key = cwt::cose_key_from_p256_verifying_key(identity.verifying_key(), &kid)
        .to_cbor_value()
        .expect("cose key");
    let mut cose_keys = Vec::new();
    ciborium::ser::into_writer(
        &ciborium::value::Value::Array(vec![cose_key]),
        &mut cose_keys,
    )
    .expect("cose key set");

    // The session's device key: what `cnf` names and what signs requests.
    let device = SigningKey::random(&mut OsRng);
    let point = device.verifying_key().to_encoded_point(false);
    let (x, y): ([u8; 32], [u8; 32]) = ((*point.x().unwrap()).into(), (*point.y().unwrap()).into());

    let token = |online_play: bool, aud: &str, iat: i64, exp: i64| GameToken {
        iss: issuer.into(),
        sub: "5c1f0e7a-2b8d-4c0f-9a51-3f2b6d8e4a10".into(),
        aud: aud.into(),
        iat,
        exp,
        cti: *uuid::Uuid::new_v4().as_bytes(),
        x,
        y,
        handle: "alice.arkavo.social".into(),
        online_play,
    };
    let verify = |bytes: &[u8]| game_token::verify(bytes, &keys, issuer, audience, now, SKEW);

    // Accepted.
    let mut accepted = Vec::new();
    let mut with_pass_text = String::new();
    for (name, online_play) in [("with_pass", true), ("without_pass", false)] {
        let t = token(online_play, audience, now, now + 900);
        let bytes = game_token::mint(&t, &identity, &kid).expect("mint");
        assert_eq!(verify(&bytes).expect(name), t);
        if online_play {
            with_pass_text = text(&bytes);
        }
        accepted.push(json!({
            "name": name,
            "token": text(&bytes),
            "iss": t.iss, "sub": t.sub, "aud": t.aud, "iat": t.iat, "exp": t.exp,
            "arkavo_handle": t.handle,
            "online_play": online_play,
        }));
    }

    // Request proofs for the token with the pass.
    let pass = token(true, audience, now, now + 900);
    let proofs: Vec<Value> = [
        (
            "GET",
            "/v1/wars/example",
            &b""[..],
            "no body: the hash of the empty string",
        ),
        (
            "POST",
            "/v1/runs",
            &br#"{"requestId":"7f9c"}"#[..],
            "a JSON body, hashed as sent",
        ),
        (
            "GET",
            "/v1/wars?game=example&page=2",
            &b""[..],
            "a query is part of the path line",
        ),
        ("GET", "/", &b""[..], "an empty path is /"),
    ]
    .into_iter()
    .map(|(method, path, body, note)| {
        let message =
            game_token::request_message(audience, method, path, now, body, &with_pass_text);
        let signature = raw_signature(&device, &message);
        assert!(game_token::request_proof_verifies(
            &pass,
            &with_pass_text,
            method,
            path,
            body,
            now,
            &signature,
            now,
            SKEW
        ));
        json!({
            "note": note, "method": method, "path": path, "t": now,
            "body_base64url": b64(body),
            "token": "accepted.with_pass",
            "message": message,
            "signature": signature,
        })
    })
    .collect();

    // Refused.
    let stranger = SigningKey::random(&mut OsRng);
    let stranger_kid = thumbprint_kid(stranger.verifying_key()).expect("kid");
    let ok = token(true, audience, now, now + 900);
    let mut refused = Vec::new();
    let mut refuse = |name: &str, why: &str, bytes: Vec<u8>, expected: fn(&CwtError) -> bool| {
        let err = verify(&bytes).expect_err(name);
        assert!(expected(&err), "{name}: {err}");
        refused.push(json!({ "name": name, "why": why, "token": text(&bytes) }));
    };
    refuse(
        "wrong_audience",
        "minted for another game server",
        game_token::mint(
            &token(true, "https://other-game.example", now, now + 900),
            &identity,
            &kid,
        )
        .unwrap(),
        |e| matches!(e, CwtError::AudienceMismatch),
    );
    refuse(
        "expired",
        "exp is more than the skew in the past",
        game_token::mint(
            &token(true, audience, now - 2_000, now - 1_100),
            &identity,
            &kid,
        )
        .unwrap(),
        |e| matches!(e, CwtError::Expired),
    );
    refuse(
        "not_yet_valid",
        "iat is more than the skew in the future",
        game_token::mint(
            &token(true, audience, now + 600, now + 1_500),
            &identity,
            &kid,
        )
        .unwrap(),
        |e| matches!(e, CwtError::NotYetValid),
    );
    refuse(
        "lifetime_over_an_hour",
        "exp - iat is more than 3600",
        game_token::mint(&token(true, audience, now, now + 3_601), &identity, &kid).unwrap(),
        |e| matches!(e, CwtError::Malformed),
    );
    refuse(
        "unknown_kid",
        "signed by a key whose kid is not in the set",
        game_token::mint(&ok, &stranger, &stranger_kid).unwrap(),
        |e| matches!(e, CwtError::UnknownKey),
    );
    refuse(
        "wrong_key_same_kid",
        "claims the set's kid, signed by another key",
        game_token::mint(&ok, &stranger, &kid).unwrap(),
        |e| matches!(e, CwtError::InvalidSignature),
    );
    refuse(
        "no_content_type",
        "an ordinary session CWT for the same audience: no protected content type",
        cwt::mint(
            &cwt::ArkavoClaims::oidc_access(issuer, &ok.sub, audience, 1),
            &identity,
            &kid,
        )
        .unwrap(),
        |e| matches!(e, CwtError::Malformed),
    );
    refuse(
        "other_content_type",
        "an owner-KAS token: another protected content type",
        authnz_rs::owner_kas_token::mint(
            &authnz_rs::owner_kas_token::OwnerKasToken {
                iss: issuer.into(),
                sub: ok.sub.clone(),
                route_id: "01JC5Z8Q4M7N2P3R6S9T0V1W2X".into(),
                iat: now,
                exp: now + 900,
                cti: [1; 16],
                x,
                y,
                handle: ok.handle.clone(),
            },
            &identity,
            &kid,
        )
        .unwrap(),
        |e| matches!(e, CwtError::Malformed),
    );
    {
        let bytes = game_token::mint(&ok, &identity, &kid).unwrap();
        refuse(
            "untagged",
            "the COSE_Sign1 without CBOR tag 61",
            bytes[cwt::CWT_TAG_PREFIX.len()..].to_vec(),
            |_| true,
        );
    }

    let out = json!({
        "about": "Generated by authnz-rs examples/game_token_vectors.rs. Every key was made for \
                  this file and is in it. Never a production key. Do not commit this file.",
        "contract": "docs/game-token.md",
        "generated_at": now,
        "verify_at": now,
        "skew_seconds": SKEW,
        "issuer": issuer,
        "audience": audience,
        "content_type": game_token::CONTENT_TYPE,
        "encoding": "tokens are base64url without padding of CBOR tag 61 around a COSE_Sign1; \
                     signatures are base64url without padding of raw r||s (64 bytes)",
        "identity": {
            "kid_hex": hex::encode(&kid),
            "cose_key_set_base64url": b64(&cose_keys),
            "cose_key_set_note": "the body /.well-known/cose-keys would serve for this key \
                                  (application/cose-key-set+cbor)",
        },
        "device_key": {
            "note": "the session device key: cnf of every token here, signer of every proof",
            "private_scalar_base64url": b64(&device.to_bytes()),
            "public_x963_base64url": b64(point.as_bytes()),
        },
        "accepted": accepted,
        "request_proofs": {
            "format": "arkavo-game-request-v1\\n<audience>\\n<METHOD>\\n<path>\\n<t>\\n<base64url \
                       sha256(body)>\\n<base64url sha256(token text)>, joined by \\n, no trailing \
                       newline; t is accepted within skew_seconds of the server's clock",
            "proofs": proofs,
        },
        "refused": refused,
    });
    std::fs::create_dir_all(&dir).expect("output directory");
    let path = std::path::Path::new(&dir).join("game-token-vectors.json");
    std::fs::write(&path, serde_json::to_string_pretty(&out).unwrap()).expect("write");
    println!("{}", path.display());
}
